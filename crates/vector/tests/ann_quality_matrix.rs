//! ANN quality matrix: declared recall methodology over independently
//! generated distributions.
//!
//! ## Fixture provenance
//!
//! Every dataset below is generated by this file's own xorshift64* PRNG
//! (never by index code) from an explicit seed. Four distributions cover
//! the failure modes a "tie-free random ladder" misses:
//!
//! - `uniform` — generic cloud, no structure (baseline selectivity).
//! - `clusters` — 8 gaussian clusters: queries concentrate near one mode.
//! - `duplicates` — exact copies of 16 base vectors: distance ties are
//!   deliberate, so `(distance, row_id)` order is exercised, not luck.
//! - `tight` — lattice spacing around 1e-4: near-ties and near-degenerate
//!   geometry that quantized indexes cannot separate confidently.
//!
//! Row ids are strided (`7*i + 3`) so "returned position" bugs cannot pass
//! as "returned id" coincidences. Query families vary selectivity: an exact
//! stored row (distance ties), a near copy, a fresh random point, and the
//! stored row's antipode (far, low selectivity). Dimensions span `3` (tiny
//! pre-quantization width), `8` (PQ's default segment count), and `128`
//! (production-scale embedding width). `ivf_pq` is exercised only on
//! dimensions its default 8 segments divide — the same precondition the
//! DDL envelope enforces.
//!
//! ## Recall methodology (declared)
//!
//! `recall@k = |ANN_k ∩ ORACLE_k| / k`, where `ORACLE_k` is the exact
//! [`FlatIndex`] top-k over the same rows and metric. It is macro-averaged
//! over the query families of a dataset (set membership, so ordering does
//! not affect the number). Gated floors are listed in [`floor`] and were
//! calibrated with margin against the printed per-cell values on this
//! fixture set; the printed line is the evidence, the assertion is the
//! regression tripwire. Ordering is asserted separately: non-decreasing
//! distance, ties broken by ascending `row_id`.
//!
//! Disabling-rediscovery: `SET vector.ann_enabled = off` in SQL gives the
//! exact baseline on demand; here the baseline is in-process [`FlatIndex`].
//!
//! ## Measured findings (calibrated 2026-10-16)
//!
//! The matrix surfaces honest quality shape rather than uniform wins;
//! see the printed lines for exact cells:
//!
//! - `ivf_pq` + cosine at dim 8 is the weakest dense cell (pre-rerank
//!   recall 0.10–0.50): 8 one-lane codebooks lose the norm detail cosine
//!   needs. L2/Dot stay ≥ 0.98; the executor reranks from authoritative
//!   rows with oversampling.
//! - `diskann`'s beam search (width 64) drops on `tight` geometry
//!   (0.42–0.58) and on clustered dot/cosine cells (0.33–0.36).
//! - Binary Hamming ANN at non-word-aligned width 130 stays approximate
//!   (0.50–0.90) because the 2-bit final word fills the candidate set
//!   without ever engaging the exact fallback; widths 64/128 score 1.000.

use plomid_vector::index::binary::{BinaryAnnProbes, BinaryIndex};
use plomid_vector::index::diskann::DiskAnnIndex;
use plomid_vector::index::hnsw::HnswIndex;
use plomid_vector::index::ivf::IvfFlatIndex;
use plomid_vector::index::pq::PqIndex;
use plomid_vector::index::sq::Sq8Index;
use plomid_vector::index::{
    FlatIndex, IndexConfig, IndexKind, Metric, RowId, SearchResult, VectorIndex,
};

/// Rows per dataset. Small enough for CI, large enough that ANN structure
/// (lists, graphs, codebooks) is meaningful rather than degenerate.
const N: usize = 256;
/// Neighbours requested per query.
const K: usize = 10;

type Rows = Vec<(RowId, Vec<f32>)>;

/// Deterministic xorshift64* — independent of every index implementation.
struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Self {
        Self(seed | 1)
    }

    fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// Uniform in `[0, 1)`.
    fn unit(&mut self) -> f64 {
        (self.next_u64() >> 11) as f64 / (1u64 << 53) as f64
    }

    /// Uniform in `[-1, 1)`.
    fn sym(&mut self) -> f32 {
        (self.unit() * 2.0 - 1.0) as f32
    }

    /// Approximate standard normal via Box-Muller (u1 clamped away from 0).
    fn gauss(&mut self) -> f32 {
        let u1 = self.unit().max(1e-12);
        let u2 = self.unit();
        ((-2.0 * u1.ln()).sqrt() * (std::f64::consts::TAU * u2).cos()) as f32
    }
}

fn row_id(i: usize) -> RowId {
    7 * i as u64 + 3
}

/// Guards cosine's zero-norm exclusion from silently shrinking a fixture.
fn guard_nonzero(mut v: Vec<f32>) -> Vec<f32> {
    if v.iter().all(|x| *x == 0.0) {
        v[0] = 0.5;
    }
    v
}

fn gen_uniform(rng: &mut Rng, dim: usize) -> Rows {
    (0..N)
        .map(|i| {
            let v: Vec<f32> = (0..dim).map(|_| rng.sym()).collect();
            (row_id(i), guard_nonzero(v))
        })
        .collect()
}

fn gen_clusters(rng: &mut Rng, dim: usize) -> Rows {
    let centers: Vec<Vec<f32>> = (0..8)
        .map(|_| (0..dim).map(|_| rng.gauss()).collect())
        .collect();
    (0..N)
        .map(|i| {
            let c = &centers[i % 8];
            let v: Vec<f32> = c.iter().map(|x| x + rng.gauss() * 0.15).collect();
            (row_id(i), guard_nonzero(v))
        })
        .collect()
}

fn gen_duplicates(rng: &mut Rng, dim: usize) -> Rows {
    // 16 base vectors, each replicated exactly: distance-0 ties on every
    // stored-row query, so `(distance, row_id)` ordering is load-bearing.
    let bases: Vec<Vec<f32>> = (0..16)
        .map(|_| (0..dim).map(|_| rng.gauss()).collect())
        .collect();
    (0..N)
        .map(|i| (row_id(i), guard_nonzero(bases[i % 16].clone())))
        .collect()
}

fn gen_tight(rng: &mut Rng, dim: usize) -> Rows {
    // Lattice with ~1e-4 lane spacing plus ~1e-5 jitter: near-ties that
    // quantized shortlists cannot separate by score alone.
    (0..N)
        .map(|i| {
            let v: Vec<f32> = (0..dim)
                .map(|j| {
                    (((i as u64 * 3 + j as u64 * 7) % 5) as f32) * 1e-4
                        + (j as f32) * 1e-5
                        + rng.sym() * 1e-5
                })
                .collect();
            (row_id(i), guard_nonzero(v))
        })
        .collect()
}

fn dataset(name: &str, dim: usize, seed: u64) -> Rows {
    let mut rng = Rng::new(seed);
    match name {
        "uniform" => gen_uniform(&mut rng, dim),
        "clusters" => gen_clusters(&mut rng, dim),
        "duplicates" => gen_duplicates(&mut rng, dim),
        "tight" => gen_tight(&mut rng, dim),
        other => panic!("unknown distribution {other}"),
    }
}

/// One query family: name plus its query vectors (fixed count per family).
struct Family {
    name: &'static str,
    queries: Vec<Vec<f32>>,
}

fn query_families(rows: &Rows, dim: usize, seed: u64) -> Vec<Family> {
    let mut rng = Rng::new(seed ^ 0xD1CE);
    // Spread the sampled rows across the dataset (cluster boundaries too).
    let sample_idx = [0usize, N / 3, 2 * N / 3];
    let stored: Vec<Vec<f32>> = sample_idx.iter().map(|i| rows[*i].1.clone()).collect();
    let near: Vec<Vec<f32>> = stored
        .iter()
        .map(|v| v.iter().map(|x| x + rng.sym() * 1e-3).collect())
        .collect();
    let random: Vec<Vec<f32>> = (0..stored.len())
        .map(|_| (0..dim).map(|_| rng.sym()).collect())
        .collect();
    let antipode: Vec<Vec<f32>> = stored
        .iter()
        .map(|v| v.iter().map(|x| -x).collect())
        .collect();
    vec![
        Family {
            name: "stored",
            queries: stored,
        },
        Family {
            name: "near",
            queries: near,
        },
        Family {
            name: "random",
            queries: random,
        },
        Family {
            name: "antipode",
            queries: antipode,
        },
    ]
}

fn index_metric(metric: plomid_vector::VectorMetric) -> Metric {
    match metric {
        plomid_vector::VectorMetric::L2 => Metric::L2,
        plomid_vector::VectorMetric::Cosine => Metric::Cosine,
        plomid_vector::VectorMetric::Dot => Metric::Dot,
        other => panic!("dense quality matrix has no {other:?} metric"),
    }
}

fn build<I, F>(ctor: F, kind: IndexKind, metric: Metric, dim: usize, rows: &Rows) -> I
where
    I: VectorIndex,
    F: FnOnce(IndexConfig) -> I,
{
    let mut index = ctor(IndexConfig::new(kind, metric, dim));
    index.build(rows).unwrap();
    index.validate().unwrap();
    index
}

/// Exact oracle over the same rows; also pins the oracle's own ordering.
fn oracle(rows: &Rows, metric: Metric, dim: usize, query: &[f32]) -> Vec<SearchResult> {
    let mut flat = FlatIndex::new(IndexConfig::new(IndexKind::Flat, metric, dim)).unwrap();
    flat.build(rows).unwrap();
    let hits = flat.search(query, K).unwrap();
    assert_ordering(&hits, "flat oracle");
    hits
}

fn recall(ann: &[SearchResult], exact: &[SearchResult]) -> f64 {
    let oracle_ids: std::collections::HashSet<RowId> = exact.iter().map(|h| h.row_id).collect();
    let hits = ann
        .iter()
        .filter(|h| oracle_ids.contains(&h.row_id))
        .count();
    hits as f64 / exact.len().max(1) as f64
}

/// Declared ordering rule: non-decreasing distance; exact ties by row id.
fn assert_ordering(hits: &[SearchResult], ctx: &str) {
    for w in hits.windows(2) {
        let (a, b) = (&w[0], &w[1]);
        assert!(
            a.distance <= b.distance,
            "{ctx}: distance regressed {} -> {}",
            a.distance,
            b.distance
        );
        if a.distance == b.distance {
            assert!(
                a.row_id < b.row_id,
                "{ctx}: tie between ids {} and {} not row-id ordered",
                a.row_id,
                b.row_id
            );
        }
    }
}

/// Declared recall floors per (method, distribution, metric, dim),
/// calibrated with margin against the printed per-cell values (see the
/// module docs for the methodology).
///
/// Calibration evidence (N=256, K=10, debug build; worst cell per bucket):
///
/// - `hnsw`: 0.975 worst (tight/dim3/Dot) → floor 0.90.
/// - `ivf_sq`: 0.917 worst (tight/dim3/Cosine) → floor 0.85.
/// - `ivf_flat` runs its production default `nprobe = 4 / nlist = 16`, so
///   recall is distribution-bound by construction: uniform 0.58–1.00,
///   clusters 0.79–1.00, duplicates 0.50–1.00, tight 0.83–1.00.
/// - `ivf_pq` is weakest on cosine at low dims, where normalization error
///   dominates the 8 one-lane codebooks: tight/dim8 0.10, clusters/dim8
///   0.36, uniform/dim8 0.50; L2/Dot stay ≥ 0.98 at every cell. This is a
///   measured property of the global-quantized scan (no inverted lists),
///   not a wiring fluke.
/// - `diskann`'s beam search drops on `tight` geometry (0.42–0.58) and in
///   clustered dot/cosine cells (0.33–0.36) at beam width 64.
///
/// The floors are tripwires with margin for platform f32 drift, not
/// targets; raising a floor should follow a changed printed value.
fn floor(method: &str, dist: &str, metric: &str, dim: usize) -> f64 {
    match (method, dist) {
        ("hnsw", _) => 0.90,
        ("ivf_sq", _) => 0.85,
        ("ivf_flat", "uniform") => 0.45,
        ("ivf_flat", "clusters") => 0.65,
        ("ivf_flat", "duplicates") => 0.35,
        ("ivf_flat", "tight") => 0.70,
        ("ivf_pq", _) if metric == "Cosine" && dim <= 8 => 0.05,
        ("ivf_pq", _) if metric == "Cosine" => 0.30,
        ("ivf_pq", _) => 0.90,
        ("diskann", "uniform") => 0.90,
        ("diskann", "duplicates") => 0.60,
        ("diskann", "clusters") => 0.25,
        ("diskann", "tight") => 0.30,
        // Unlisted (method, distribution) pairs: reported, not gated.
        _ => 0.0,
    }
}

#[test]
fn dense_methods_quality_across_distributions() {
    const DISTS: [&str; 4] = ["uniform", "clusters", "duplicates", "tight"];
    const DIMS: [usize; 3] = [3, 8, 128];
    const METRICS: [plomid_vector::VectorMetric; 3] = [
        plomid_vector::VectorMetric::L2,
        plomid_vector::VectorMetric::Cosine,
        plomid_vector::VectorMetric::Dot,
    ];
    // Distinct seeds per (distribution, dim) cell so datasets never repeat
    // across widths. Printed on failure via the assertion context.
    let seed_of = |dist: usize, dim: usize| -> u64 {
        0xA11CE_0000 ^ ((dist as u64) << 24) ^ ((dim as u64) << 8) ^ 0x9E37
    };

    let mut worst: std::collections::BTreeMap<String, f64> = std::collections::BTreeMap::new();
    for (di, dist) in DISTS.iter().enumerate() {
        for dim in DIMS {
            let rows = dataset(dist, dim, seed_of(di, dim));
            let families = query_families(&rows, dim, seed_of(di, dim));
            for metric in METRICS {
                let im = index_metric(metric);
                // Per-query oracle + recall accumulation per method.
                let mut method_acc: std::collections::BTreeMap<&str, (f64, usize)> =
                    std::collections::BTreeMap::new();

                let hnsw = build(
                    |c| HnswIndex::new(c).unwrap(),
                    IndexKind::Hnsw,
                    im,
                    dim,
                    &rows,
                );
                let ivf_flat = build(
                    |c| IvfFlatIndex::new(c).unwrap(),
                    IndexKind::IvfFlat,
                    im,
                    dim,
                    &rows,
                );
                let sq = build(
                    |c| Sq8Index::new(c).unwrap(),
                    IndexKind::IvfSq,
                    im,
                    dim,
                    &rows,
                );
                let pq = if dim % plomid_vector::index::pq::PQ_DEFAULT_SEGMENTS == 0 {
                    Some(build(
                        |c| PqIndex::new(c).unwrap(),
                        IndexKind::IvfPq,
                        im,
                        dim,
                        &rows,
                    ))
                } else {
                    None
                };
                let diskann = {
                    let dir = std::env::temp_dir().join(format!(
                        "plomid-ann-quality-{}-{}-{}-{}",
                        dist,
                        dim,
                        metric as u8,
                        std::process::id()
                    ));
                    let _ = std::fs::remove_dir_all(&dir);
                    let mut index =
                        DiskAnnIndex::new(IndexConfig::new(IndexKind::DiskAnn, im, dim), &dir)
                            .unwrap();
                    index.build(&rows).unwrap();
                    index.validate().unwrap();
                    index
                };

                for family in &families {
                    for query in &family.queries {
                        let exact = oracle(&rows, im, dim, query);
                        for (name, hits) in [
                            ("hnsw", hnsw.search(query, K).unwrap()),
                            ("ivf_flat", ivf_flat.search(query, K).unwrap()),
                            ("ivf_sq", sq.search(query, K).unwrap()),
                            ("diskann", diskann.search(query, K).unwrap()),
                        ] {
                            let ctx = format!(
                                "{name}/{dist}/dim{dim}/{metric:?}/{}/seed={:#x}",
                                family.name,
                                seed_of(di, dim)
                            );
                            assert_ordering(&hits, &ctx);
                            let acc = method_acc.entry(name).or_insert((0.0, 0));
                            acc.0 += recall(&hits, &exact);
                            acc.1 += 1;
                        }
                        if let Some(pq) = &pq {
                            let hits = pq.search(query, K).unwrap();
                            let ctx = format!(
                                "ivf_pq/{dist}/dim{dim}/{metric:?}/{}/seed={:#x}",
                                family.name,
                                seed_of(di, dim)
                            );
                            assert_ordering(&hits, &ctx);
                            let acc = method_acc.entry("ivf_pq").or_insert((0.0, 0));
                            acc.0 += recall(&hits, &exact);
                            acc.1 += 1;
                        }
                    }
                }
                for (name, (sum, count)) in &method_acc {
                    let avg = sum / *count as f64;
                    let key = (*name).to_string();
                    worst
                        .entry(key)
                        .and_modify(|w| *w = w.min(avg))
                        .or_insert(avg);
                    let metric_name = format!("{metric:?}");
                    eprintln!(
                        "ann-quality {name:8} {dist:10} dim{dim:<3} {metric:?}: recall@{K}={avg:.3} over {count} queries"
                    );
                    assert!(
                        avg >= floor(name, dist, &metric_name, dim),
                        "{name} {dist} dim{dim} {metric:?}: recall@{K} {avg:.3} below floor {}",
                        floor(name, dist, &metric_name, dim)
                    );
                }
            }
        }
    }
    eprintln!("ann-quality floors (worst cell per method): {worst:?}");
}

#[test]
fn binary_hamming_quality_across_distributions() {
    // Bit-pattern generators: balanced random, clustered (few flips around
    // bases), and exact duplicates. Dims: 64 (one word), 128 (two), 130
    // (three words with padding bits live).
    fn bits<R: FnMut(usize) -> bool>(dim: usize, mut f: R) -> Vec<f32> {
        (0..dim).map(|i| if f(i) { 1.0f32 } else { 0.0 }).collect()
    }
    let mut summary: Vec<(String, f64)> = Vec::new();
    for dim in [64usize, 128, 130] {
        for dist in ["balanced", "clustered", "duplicates"] {
            let seed = 0xB1B1_0000 ^ ((dim as u64) << 16) ^ (dist.len() as u64);
            let mut rng = Rng::new(seed);
            let bases: Vec<Vec<f32>> = (0..16).map(|_| bits(dim, |_| rng.unit() < 0.5)).collect();
            let rows_f32: Vec<Vec<f32>> = (0..N)
                .map(|i| match dist {
                    "balanced" => bits(dim, |_| rng.unit() < 0.5),
                    "clustered" => {
                        let mut v = bases[i % 16].clone();
                        for _ in 0..3 {
                            let b = (rng.next_u64() as usize) % dim;
                            v[b] = 1.0 - v[b];
                        }
                        v
                    }
                    "duplicates" => bases[i % 16].clone(),
                    _ => unreachable!(),
                })
                .collect();

            // Pack into the index (row id stride marks position mixups).
            // Generic trait build binarizes at `> 0.0`; the ANN entry point
            // takes packed words, packed here independently of the index.
            let rows_with_ids: Rows = rows_f32
                .iter()
                .enumerate()
                .map(|(i, v)| (row_id(i), v.clone()))
                .collect();
            let mut index =
                BinaryIndex::new(IndexConfig::new(IndexKind::Binary, Metric::Hamming, dim))
                    .unwrap();
            index.build(&rows_with_ids).unwrap();
            index.validate().unwrap();

            let sample = [0usize, N / 3, 2 * N / 3];
            let queries: Vec<(String, Vec<f32>)> = sample
                .iter()
                .flat_map(|i| {
                    let stored = rows_f32[*i].clone();
                    let near: Vec<f32> = stored
                        .iter()
                        .map(|x| if rng.unit() < 0.03 { 1.0 - x } else { *x })
                        .collect();
                    let random = bits(dim, |_| rng.unit() < 0.5);
                    vec![
                        ("stored".to_string(), stored),
                        ("near".to_string(), near),
                        ("random".to_string(), random),
                    ]
                })
                .collect();

            let bounds = |query: &[f32]| -> Vec<u8> {
                query
                    .chunks(8)
                    .map(|c| {
                        let mut b = 0u8;
                        for (k, bit) in c.iter().enumerate() {
                            if *bit > 0.0 {
                                b |= 1 << (7 - k);
                            }
                        }
                        b
                    })
                    .collect()
            };

            let mut sum = 0.0;
            for (family, query) in &queries {
                let exact = index.search(query, K).unwrap();
                assert_ordering(&exact, "binary exact");
                let packed = BinaryIndex::pack_bits(&bounds(query), dim).unwrap();
                let ann = index
                    .ann_search_words(&packed, K, BinaryAnnProbes::default())
                    .unwrap();
                let ctx = format!("binary/{dist}/dim{dim}/{family}/seed={seed:#x}");
                assert_ordering(&ann, &ctx);
                let r = recall(&ann, &exact);
                eprintln!(
                    "ann-quality binary-detail {dist:10} dim{dim:<3} {family:8}: recall={r:.3}"
                );
                // Measured floors: word-aligned widths (64, 128) scored
                // 1.000 in every cell, so they gate at 0.90. Width 130
                // leaves a 2-bit final word whose inverted list holds at
                // most 4 distinct values, so block probes alone easily
                // exceed `k` and the exact fallback never engages: worst
                // measured family recall is 0.500 (duplicates/random), so
                // that width gates at 0.40. See the module docs.
                let gate = if dim <= 128 { 0.90 } else { 0.40 };
                assert!(
                    r >= gate,
                    "{ctx}: hamming ANN recall@{K} {r:.3} below {gate} (ann={ann:?} exact={exact:?})"
                );
                sum += r;
            }
            let avg = sum / queries.len() as f64;
            eprintln!("ann-quality binary  {dist:10} dim{dim:<3}: recall@{K}={avg:.3}");
            summary.push((format!("{dist}/dim{dim}"), avg));
        }
    }
    let worst = summary
        .iter()
        .map(|(_, r)| *r)
        .fold(f64::INFINITY, f64::min);
    eprintln!("ann-quality binary worst cell: {worst:.3}");
}
