//! Expression parsing with standard SQL operator precedence.
//!
//! Precedence (lowest to highest) matches PostgreSQL:
//! `OR` < `AND` < `NOT` < comparison/predicates < additive < multiplicative
//! < unary < primary. Parentheses override the default grouping.

use super::json::{
    is_trailing_clause_ahead, parse_is_json_predicate, parse_json_call_args,
    parse_json_object_pairs, parse_json_table_call,
};
use super::{ParseError, Parser};
use crate::{
    ast::{ComparisonOperator, Expression, OrderByItem, Quantifier, Statement, Value},
    lexer::{Keyword, TokenKind},
};

/// Parses a full boolean-valued expression (the `OR` level).
pub fn parse_expression(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    // Guarded: every parenthesized group, function argument, subscript index,
    // and CASE operand funnels through here, so this is the nesting choke
    // point for expression syntax (see `MAX_EXPRESSION_NESTING_DEPTH`).
    parser.nested(|parser| {
        let mut left = parse_and(parser)?;
        while parser.check(TokenKind::Keyword(Keyword::Or)) {
            parser.advance();
            let right = parse_and(parser)?;
            left = Expression::Or(Box::new(left), Box::new(right));
        }
        Ok(left)
    })
}

fn parse_and(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let mut left = parse_not(parser)?;
    while parser.check(TokenKind::Keyword(Keyword::And)) {
        parser.advance();
        let right = parse_not(parser)?;
        left = Expression::And(Box::new(left), Box::new(right));
    }
    Ok(left)
}

fn parse_not(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    if parser.check(TokenKind::Keyword(Keyword::Not)) {
        parser.advance();
        // Guarded: `NOT NOT …` self-recursion bypasses `parse_expression`.
        return parser.nested(|parser| Ok(Expression::Not(Box::new(parse_not(parser)?))));
    }
    parse_predicate(parser)
}

fn parse_predicate(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parse_comparison(parser)
}

fn parse_comparison(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let left = parse_concat(parser)?;
    // PostgreSQL emits this form in catalog introspection queries generated by
    // psql: `value OPERATOR(pg_catalog.~) pattern`.  It is ordinary operator
    // syntax with an explicit schema qualification, not a client-specific
    // command, so resolve it through the normal expression path.
    if parser.check(TokenKind::Identifier) && parser.peek().lexeme.eq_ignore_ascii_case("operator")
    {
        let snapshot = parser.pos;
        parser.advance();
        if parser.check(TokenKind::LParen) {
            parser.advance();
            let _schema = parser.consume(TokenKind::Identifier, "operator schema")?;
            parser.consume(TokenKind::Dot, ".")?;
            let operator = parser.peek().clone();
            if matches!(
                operator.kind,
                TokenKind::RegexMatch
                    | TokenKind::RegexMatchInsensitive
                    | TokenKind::RegexNotMatch
                    | TokenKind::RegexNotMatchInsensitive
            ) {
                parser.advance();
                parser.consume(TokenKind::RParen, ")")?;
                let right = parse_concat(parser)?;
                if parser.check(TokenKind::Keyword(Keyword::Collate)) {
                    parser.advance();
                    let _ = parser.parse_qualified_identifier("collation name")?;
                }
                let name = match operator.kind {
                    TokenKind::RegexMatch => "regex_match",
                    TokenKind::RegexMatchInsensitive => "regex_match_i",
                    TokenKind::RegexNotMatch => "regex_not_match",
                    TokenKind::RegexNotMatchInsensitive => "regex_not_match_i",
                    _ => unreachable!(),
                };
                return Ok(Expression::FunctionCall {
                    name: name.to_string(),
                    args: vec![left, right],
                    distinct: false,
                    filter: None,
                    order_by: Vec::new(),
                    returning: None,
                    null_handling: None,
                    unique_keys: None,
                });
            }
        }
        parser.pos = snapshot;
    }
    let kind = parser.peek().kind;
    // Check for quantified comparison: <op> ANY/SOME/ALL (...)
    // The parenthesised RHS may be either:
    //   - a SELECT subquery:  x > ANY (SELECT y FROM t)
    //   - an array expression: x = ANY (ARRAY[1,2,3]) or x = ANY(array_col)
    // The pre-existing behaviour for = / <> with an array RHS is preserved
    // via the any_equal/all_equal function-call path. All other operators,
    // and all subquery RHS forms, use the QuantifiedComparison AST node.
    if matches!(
        kind,
        TokenKind::Eq
            | TokenKind::NotEq
            | TokenKind::Lt
            | TokenKind::Le
            | TokenKind::Gt
            | TokenKind::Ge
    ) && parser.tokens.get(parser.pos + 1).is_some_and(|token| {
        matches!(
            token.kind,
            TokenKind::Keyword(Keyword::Any)
                | TokenKind::Keyword(Keyword::All)
                | TokenKind::Keyword(Keyword::Some)
        )
    }) {
        let operator_token = parser.peek().clone();
        parser.advance();
        let quantifier_token = parser.peek().clone();
        parser.advance();

        // SOME is a synonym for ANY
        let quantifier = if matches!(quantifier_token.kind, TokenKind::Keyword(Keyword::Some)) {
            Quantifier::Any
        } else if matches!(quantifier_token.kind, TokenKind::Keyword(Keyword::All)) {
            Quantifier::All
        } else {
            Quantifier::Any
        };

        parser.consume(TokenKind::LParen, "(")?;
        let is_subquery = parser.check(TokenKind::Keyword(Keyword::Select));
        if is_subquery {
            // Parse the subquery, not a regular expression
            let subquery = super::select::parse_select(parser)?;
            parser.consume(TokenKind::RParen, ")")?;

            let operator = match operator_token.kind {
                TokenKind::Eq => ComparisonOperator::Equal,
                TokenKind::NotEq => ComparisonOperator::NotEqual,
                TokenKind::Lt => ComparisonOperator::Less,
                TokenKind::Le => ComparisonOperator::LessOrEqual,
                TokenKind::Gt => ComparisonOperator::Greater,
                TokenKind::Ge => ComparisonOperator::GreaterOrEqual,
                _ => unreachable!(),
            };

            return Ok(Expression::QuantifiedComparison {
                left: Box::new(left),
                operator,
                quantifier,
                subquery: Box::new(subquery),
            });
        }
        // Array RHS: preserve the legacy any_equal/all_equal path for = / <>
        // so existing `= ANY(array)` / `<> ALL(array)` tests keep working.
        // This includes parenthesised expressions, e.g. `= ANY ((SELECT ...))`.
        if matches!(operator_token.kind, TokenKind::Eq | TokenKind::NotEq) {
            // `= ANY ((SELECT ...))` is a parenthesised subquery, not an
            // array expression: route it to QuantifiedComparison.
            if parser.check(TokenKind::LParen)
                && parser
                    .tokens
                    .get(parser.pos + 1)
                    .is_some_and(|t| matches!(t.kind, TokenKind::Keyword(Keyword::Select)))
            {
                parser.advance();
                let subquery = super::select::parse_select(parser)?;
                parser.consume(TokenKind::RParen, ")")?;
                parser.consume(TokenKind::RParen, ")")?;
                let operator = match operator_token.kind {
                    TokenKind::Eq => ComparisonOperator::Equal,
                    TokenKind::NotEq => ComparisonOperator::NotEqual,
                    _ => unreachable!(),
                };
                return Ok(Expression::QuantifiedComparison {
                    left: Box::new(left),
                    operator,
                    quantifier,
                    subquery: Box::new(subquery),
                });
            }
            let right = parse_concat(parser)?;
            parser.consume(TokenKind::RParen, ")")?;
            let all = matches!(quantifier_token.kind, TokenKind::Keyword(Keyword::All));
            let name = match (operator_token.kind, all) {
                (TokenKind::Eq, false) => "any_equal",
                (TokenKind::Eq, true) => "all_equal",
                (TokenKind::NotEq, false) => "any_not_equal",
                (TokenKind::NotEq, true) => "all_not_equal",
                _ => unreachable!(),
            };
            return Ok(Expression::FunctionCall {
                name: name.into(),
                args: vec![left, right],
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            });
        }
        // Non-equality operators with a non-subquery RHS, e.g.
        // `> ANY (array_expr)`: represent as a quantified comparison over a
        // synthetic `SELECT <expr>` subquery so evaluation reuses the
        // subquery ANY/ALL semantics.
        let rhs = parse_concat(parser)?;
        parser.consume(TokenKind::RParen, ")")?;
        let operator = match operator_token.kind {
            TokenKind::Eq => ComparisonOperator::Equal,
            TokenKind::NotEq => ComparisonOperator::NotEqual,
            TokenKind::Lt => ComparisonOperator::Less,
            TokenKind::Le => ComparisonOperator::LessOrEqual,
            TokenKind::Gt => ComparisonOperator::Greater,
            TokenKind::Ge => ComparisonOperator::GreaterOrEqual,
            _ => unreachable!(),
        };
        let subquery = Statement::Select {
            targets: vec![crate::ast::SelectTarget::Expr {
                expr: rhs,
                alias: None,
            }],
            distinct: false,
            distinct_on: None,
            from: None,
            where_expr: None,
            group_by: None,
            having: None,
            order_by: Vec::new(),
            limit: None,
            offset: None,
        };
        return Ok(Expression::QuantifiedComparison {
            left: Box::new(left),
            operator,
            quantifier,
            subquery: Box::new(subquery),
        });
    }
    match kind {
        TokenKind::Eq => {
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::Equal(Box::new(left), Box::new(right)))
        }
        TokenKind::NotEq => {
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::NotEqual(Box::new(left), Box::new(right)))
        }
        TokenKind::Lt => {
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::Less(Box::new(left), Box::new(right)))
        }
        TokenKind::Le => {
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::LessOrEqual(Box::new(left), Box::new(right)))
        }
        TokenKind::Gt => {
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::Greater(Box::new(left), Box::new(right)))
        }
        TokenKind::Ge => {
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::GreaterOrEqual(Box::new(left), Box::new(right)))
        }
        // Vector distance operators lower to their scalar-function spellings
        // (same precedent as the JSON operators below): one implementation
        // backs every spelling, so `<=>` and `cosine_distance` share catalog
        // persistence, evaluation, ANN detection and EXPLAIN paths.
        // `<#>` is negative inner product, so ascending ORDER BY stays
        // nearest-first like every other distance spelling.
        TokenKind::VectorCosine
        | TokenKind::VectorL2
        | TokenKind::VectorDot
        | TokenKind::VectorHamming
        | TokenKind::VectorJaccard => {
            let name = match kind {
                TokenKind::VectorCosine => "cosine_distance",
                TokenKind::VectorL2 => "l2_distance",
                TokenKind::VectorDot => "neg_inner_product",
                TokenKind::VectorHamming => "hamming_distance",
                TokenKind::VectorJaccard => "jaccard_distance",
                _ => unreachable!(),
            };
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::FunctionCall {
                name: name.into(),
                args: vec![left, right],
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::Contains
        | TokenKind::ContainedBy
        | TokenKind::JsonExists
        | TokenKind::JsonExistsAny
        | TokenKind::JsonExistsAll
        | TokenKind::JsonPathExistsOp
        | TokenKind::JsonPathMatchOp => {
            // JSON containment (`@>`, `<@`), existence (`?`, `?|`, `?&`) and the
            // JSONPath operators (`@?`, `@@`) are all lowered to the scalar
            // functions named in `super::json` so that one implementation backs
            // every spelling. They share this precedence level so mixed boolean
            // expressions compose the way SQL/JSON expects.
            let operator = parser.peek().lexeme.clone();
            parser.advance();
            let right = parse_concat(parser)?;
            Ok(Expression::FunctionCall {
                name: super::json::predicate_function(&operator).to_string(),
                args: vec![left, right],
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::RegexMatch
        | TokenKind::RegexMatchInsensitive
        | TokenKind::RegexNotMatch
        | TokenKind::RegexNotMatchInsensitive => {
            let operator = parser.peek().kind;
            parser.advance();
            let right = parse_concat(parser)?;
            let name = match operator {
                TokenKind::RegexMatch => "regex_match",
                TokenKind::RegexMatchInsensitive => "regex_match_i",
                TokenKind::RegexNotMatch => "regex_not_match",
                TokenKind::RegexNotMatchInsensitive => "regex_not_match_i",
                _ => unreachable!(),
            };
            Ok(Expression::FunctionCall {
                name: name.to_string(),
                args: vec![left, right],
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::Keyword(Keyword::Is) => {
            parser.advance();
            let not_null = if parser.check(TokenKind::Keyword(Keyword::Not)) {
                parser.advance();
                true
            } else {
                false
            };
            // IS [NOT] NULL
            if parser.check(TokenKind::Keyword(Keyword::Null)) {
                parser.advance();
                return Ok(if not_null {
                    Expression::IsNotNull(Box::new(left))
                } else {
                    Expression::IsNull(Box::new(left))
                });
            }
            // IS [NOT] JSON [VALUE|OBJECT|ARRAY|SCALAR]
            if parser.check_keyword(Keyword::Json) {
                return parse_is_json_predicate(parser, left, not_null);
            }
            // IS [NOT] TRUE/FALSE/UNKNOWN
            if parser.check_keyword(Keyword::True)
                || parser.check_keyword(Keyword::False)
                || parser.check_keyword(Keyword::Unknown)
            {
                let kind = if parser.check_keyword(Keyword::True) {
                    crate::ast::IsBooleanKind::True
                } else if parser.check_keyword(Keyword::False) {
                    crate::ast::IsBooleanKind::False
                } else {
                    crate::ast::IsBooleanKind::Unknown
                };
                parser.advance();
                return Ok(Expression::IsBoolean {
                    expr: Box::new(left),
                    kind,
                    negated: not_null,
                });
            }
            Err(ParseError::unexpected(
                parser.peek(),
                "NULL, JSON, TRUE, FALSE, or UNKNOWN after IS",
            ))
        }
        TokenKind::Keyword(Keyword::Not) => {
            // NOT IN, NOT BETWEEN, NOT LIKE, IS NOT DISTINCT FROM, etc.
            let snapshot = parser.pos;
            parser.advance();
            if parser.check(TokenKind::Keyword(Keyword::In)) {
                parser.advance();
                let mut inner = parse_in_list_with_left(parser, left)?;
                if let Expression::In { negated, .. } = &mut inner {
                    *negated = true;
                }
                return Ok(inner);
            }
            if parser.check(TokenKind::Keyword(Keyword::Between)) {
                parser.advance();
                let low = parse_concat(parser)?;
                parser.consume(TokenKind::Keyword(Keyword::And), "AND")?;
                let high = parse_concat(parser)?;
                return Ok(Expression::Between {
                    expr: Box::new(left),
                    low: Box::new(low),
                    high: Box::new(high),
                    negated: true,
                });
            }
            if parser.check(TokenKind::Keyword(Keyword::Like))
                || parser.check(TokenKind::Keyword(Keyword::Ilike))
                || parser.check(TokenKind::Keyword(Keyword::Similar))
            {
                if parser.check(TokenKind::Keyword(Keyword::Similar)) {
                    parser.advance();
                    parser.consume(TokenKind::Keyword(Keyword::To), "TO")?;
                    let pattern = parse_concat(parser)?;
                    return Ok(Expression::FunctionCall {
                        name: "similar_not".into(),
                        args: vec![left, pattern],
                        distinct: false,
                        filter: None,
                        order_by: Vec::new(),
                        returning: None,
                        null_handling: None,
                        unique_keys: None,
                    });
                }
                let case_insensitive = parser.check(TokenKind::Keyword(Keyword::Ilike));
                parser.advance();
                let pattern = parse_concat(parser)?;
                let escape = parse_escape_clause(parser)?;
                return Ok(Expression::Like {
                    expr: Box::new(left),
                    pattern: Box::new(pattern),
                    escape,
                    negated: true,
                    case_insensitive,
                });
            }
            // Not a recognised negated predicate — rewind and treat the
            // leading NOT as belonging to an enclosing context.
            parser.pos = snapshot;
            Ok(left)
        }
        TokenKind::Keyword(Keyword::In) => {
            parser.advance();
            parse_in_list_with_left(parser, left)
        }
        TokenKind::Keyword(Keyword::Between) => {
            parser.advance();
            let low = parse_additive(parser)?;
            parser.consume(TokenKind::Keyword(Keyword::And), "AND")?;
            let high = parse_additive(parser)?;
            Ok(Expression::Between {
                expr: Box::new(left),
                low: Box::new(low),
                high: Box::new(high),
                negated: false,
            })
        }
        TokenKind::Keyword(Keyword::Like)
        | TokenKind::Keyword(Keyword::Ilike)
        | TokenKind::Keyword(Keyword::Similar) => {
            if parser.check(TokenKind::Keyword(Keyword::Similar)) {
                parser.advance();
                parser.consume(TokenKind::Keyword(Keyword::To), "TO")?;
                let pattern = parse_concat(parser)?;
                return Ok(Expression::FunctionCall {
                    name: "similar_to".into(),
                    args: vec![left, pattern],
                    distinct: false,
                    filter: None,
                    order_by: Vec::new(),
                    returning: None,
                    null_handling: None,
                    unique_keys: None,
                });
            }
            let case_insensitive = parser.check(TokenKind::Keyword(Keyword::Ilike));
            parser.advance();
            let pattern = parse_concat(parser)?;
            let escape = parse_escape_clause(parser)?;
            Ok(Expression::Like {
                expr: Box::new(left),
                pattern: Box::new(pattern),
                escape,
                negated: false,
                case_insensitive,
            })
        }
        _ => Ok(left),
    }
}

/// Parses PostgreSQL's "any other operator" level for bitwise operators
/// (`&`, `|`, `#`, `<<`, `>>`). These bind more loosely than `||` and the
/// additive operators, matching PostgreSQL's operator precedence.
fn parse_bitwise(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let mut left = parse_additive(parser)?;
    loop {
        match parser.peek().kind {
            TokenKind::Ampersand => {
                parser.advance();
                let right = parse_additive(parser)?;
                left = Expression::BitAnd(Box::new(left), Box::new(right));
            }
            TokenKind::Pipe => {
                parser.advance();
                let right = parse_additive(parser)?;
                left = Expression::BitOr(Box::new(left), Box::new(right));
            }
            TokenKind::Hash => {
                parser.advance();
                let right = parse_additive(parser)?;
                left = Expression::BitXor(Box::new(left), Box::new(right));
            }
            TokenKind::LeftShift => {
                parser.advance();
                let right = parse_additive(parser)?;
                left = Expression::ShiftLeft(Box::new(left), Box::new(right));
            }
            TokenKind::RightShift => {
                parser.advance();
                let right = parse_additive(parser)?;
                left = Expression::ShiftRight(Box::new(left), Box::new(right));
            }
            _ => break,
        }
    }
    Ok(left)
}

/// Parses PostgreSQL's general operator precedence level for `||`.
/// Additive and multiplicative operators bind more tightly, so
/// `a + b || c` groups as `(a + b) || c`.
fn parse_concat(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let mut left = parse_bitwise(parser)?;
    while parser.check(TokenKind::Concat) {
        parser.advance();
        let right = parse_bitwise(parser)?;
        left = Expression::Concat(Box::new(left), Box::new(right));
    }
    Ok(left)
}

fn parse_escape_clause(parser: &mut Parser<'_>) -> Result<Option<char>, ParseError> {
    if parser.check(TokenKind::Keyword(Keyword::Escape)) {
        parser.advance();
        let token = parser.peek().clone();
        if let TokenKind::StringLiteral = token.kind {
            parser.advance();
            let s = token.lexeme.clone();
            let mut chars = s.chars();
            let c = chars.next().ok_or_else(|| {
                ParseError::unexpected(&token, "ESCAPE must be a single character")
            })?;
            if chars.next().is_some() {
                return Err(ParseError::unexpected(
                    &token,
                    "ESCAPE must be a single character",
                ));
            }
            return Ok(Some(c));
        }
        return Err(ParseError::unexpected(&token, "ESCAPE string literal"));
    }
    Ok(None)
}

fn parse_in_list_with_left(
    parser: &mut Parser<'_>,
    left: Expression,
) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::LParen, "(")?;
    if parser.check(TokenKind::Keyword(Keyword::Select)) {
        let subquery = Box::new(super::select::parse_select(parser)?);
        parser.consume(TokenKind::RParen, ")")?;
        return Ok(Expression::In {
            expr: Box::new(left),
            list: Vec::new(),
            subquery: Some(subquery),
            negated: false,
        });
    }
    let mut list = Vec::new();
    loop {
        list.push(parse_additive(parser)?);
        if !parser.check(TokenKind::Comma) {
            break;
        }
        parser.advance();
    }
    parser.consume(TokenKind::RParen, ")")?;
    Ok(Expression::In {
        expr: Box::new(left),
        list,
        subquery: None,
        negated: false,
    })
}

fn parse_additive(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let mut left = parse_multiplicative(parser)?;
    loop {
        match parser.peek().kind {
            TokenKind::Plus => {
                parser.advance();
                let right = parse_multiplicative(parser)?;
                left = Expression::Add(Box::new(left), Box::new(right));
            }
            TokenKind::Minus => {
                parser.advance();
                let right = parse_multiplicative(parser)?;
                left = Expression::Subtract(Box::new(left), Box::new(right));
            }
            _ => break,
        }
    }
    Ok(left)
}

fn parse_multiplicative(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let mut left = parse_exponential(parser)?;
    loop {
        match parser.peek().kind {
            TokenKind::Star => {
                parser.advance();
                let right = parse_exponential(parser)?;
                left = Expression::Multiply(Box::new(left), Box::new(right));
            }
            TokenKind::Slash => {
                parser.advance();
                let right = parse_exponential(parser)?;
                left = Expression::Divide(Box::new(left), Box::new(right));
            }
            TokenKind::Percent => {
                parser.advance();
                let right = parse_exponential(parser)?;
                left = Expression::Modulo(Box::new(left), Box::new(right));
            }
            // JSON accessors bind more tightly than additive operators, matching
            // PostgreSQL's "any other operator" precedence.
            TokenKind::Arrow | TokenKind::ArrowRight => {
                let as_text = parser.peek().kind == TokenKind::ArrowRight;
                parser.advance();
                let right = parse_exponential(parser)?;
                left = Expression::JsonArrow {
                    left: Box::new(left),
                    right: Box::new(right),
                    as_text,
                };
            }
            TokenKind::HashArrow | TokenKind::HashArrowRight => {
                let as_text = parser.peek().kind == TokenKind::HashArrowRight;
                parser.advance();
                let right = parse_exponential(parser)?;
                left = Expression::FunctionCall {
                    name: super::json::accessor_function(as_text).to_string(),
                    args: vec![left, right],
                    distinct: false,
                    filter: None,
                    order_by: Vec::new(),
                    returning: None,
                    null_handling: None,
                    unique_keys: None,
                };
            }
            TokenKind::HashMinus => {
                parser.advance();
                let right = parse_exponential(parser)?;
                left = Expression::FunctionCall {
                    name: super::json::DELETE_PATH_FUNCTION.to_string(),
                    args: vec![left, right],
                    distinct: false,
                    filter: None,
                    order_by: Vec::new(),
                    returning: None,
                    null_handling: None,
                    unique_keys: None,
                };
            }
            _ => break,
        }
    }
    Ok(left)
}

fn parse_exponential(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let left = parse_unary(parser)?;
    if parser.check(TokenKind::Caret) {
        parser.advance();
        // Guarded: right-associative `^` chains self-recurse past
        // `parse_expression`.
        return parser.nested(|parser| {
            let right = parse_exponential(parser)?;
            Ok(Expression::Power(Box::new(left), Box::new(right)))
        });
    }
    Ok(left)
}

fn parse_unary(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    match parser.peek().kind {
        TokenKind::Minus => {
            parser.advance();
            // Guarded: `- - …` self-recursion bypasses `parse_expression`.
            parser.nested(|parser| Ok(Expression::Negate(Box::new(parse_unary(parser)?))))
        }
        TokenKind::Plus => {
            parser.advance();
            parser.nested(|parser| parse_unary(parser))
        }
        _ => parse_primary(parser),
    }
}

fn parse_primary(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let base = parse_primary_atom(parser)?;
    // PostgreSQL postfix `::type` casts (tightest binding).
    let mut expr = base;
    loop {
        if parser.check(TokenKind::DoubleColon) {
            parser.advance();
            let type_name = parser.parse_type_name("type name")?;
            expr = Expression::TypeCast {
                expr: Box::new(expr),
                type_name,
            };
        } else if parser.check(TokenKind::LBracket) {
            // Array subscript: `arr[1]` (1-based element access).
            parser.advance();
            let index = parse_expression(parser)?;
            parser.consume(TokenKind::RBracket, "]")?;
            expr = Expression::ArrayIndex {
                array: Box::new(expr),
                index: Box::new(index),
            };
        } else if parser.check(TokenKind::Dot) {
            // Record/attribute access: `(record).field`. Bare dotted names
            // (`table.column`) are consumed inside the atom parser; this branch
            // only fires after a parenthesised, subscripted, or cast subexpression.
            parser.advance();
            let field_token = parser.peek().clone();
            let field = match field_token.kind {
                TokenKind::Identifier => {
                    parser.advance();
                    field_token.lexeme.clone()
                }
                _ => return Err(ParseError::unexpected(&field_token, "field name")),
            };
            expr = Expression::RowField {
                expr: Box::new(expr),
                field,
            };
        } else {
            break;
        }
    }
    Ok(expr)
}

/// Parses the optional `(p)` fractional-second precision that follows a
/// temporal type keyword in a typed literal: `TIME(p)`, `TIMESTAMP(p)`,
/// `TIMESTAMPTZ(p)`. Returns `None` when the next token is not a `(` (the
/// unparameterized typed-literal forms keep working unchanged). The value is
/// validated to PostgreSQL's `0..=6` range through the existing `ParseError`
/// mechanism; out-of-range precision is rejected, never silently clamped.
fn parse_temporal_precision(parser: &mut Parser<'_>) -> Result<Option<u8>, ParseError> {
    if !parser.check(TokenKind::LParen) {
        return Ok(None);
    }
    parser.advance();
    let amount = parser
        .consume(TokenKind::IntegerLiteral, "type precision")?
        .lexeme
        .parse::<i64>()
        .map_err(|_| ParseError::unexpected(parser.peek(), "valid type precision integer"))?;
    parser.consume(TokenKind::RParen, ")")?;
    if !(0..=6).contains(&amount) {
        return Err(ParseError::Unsupported {
            message: format!("precision {amount} must be between 0 and 6"),
            detail: None,
        });
    }
    Ok(Some(amount as u8))
}

fn parse_primary_atom(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    let token = parser.peek().clone();
    match token.kind {
        TokenKind::IntegerLiteral
        | TokenKind::StringLiteral
        | TokenKind::BitLiteral
        | TokenKind::Keyword(Keyword::Null)
        | TokenKind::Keyword(Keyword::True)
        | TokenKind::Keyword(Keyword::False) => {
            let value = parse_value(parser)?;
            Ok(Expression::Literal(value))
        }
        TokenKind::Keyword(Keyword::Cast) => parse_cast_expression(parser),
        TokenKind::Keyword(Keyword::Extract) => parse_extract_expression(parser),
        TokenKind::Keyword(Keyword::Date) => {
            parser.advance();
            let s = parser
                .consume(TokenKind::StringLiteral, "DATE string literal")?
                .lexeme;
            Ok(Expression::DateLiteral(s))
        }
        TokenKind::Keyword(Keyword::Time) => {
            parser.advance();
            let precision = parse_temporal_precision(parser)?;
            let s = parser
                .consume(TokenKind::StringLiteral, "TIME string literal")?
                .lexeme;
            match precision {
                Some(p) => Ok(Expression::TypedTimeLiteral {
                    text: s,
                    precision: p,
                }),
                None => Ok(Expression::TimeLiteral(s)),
            }
        }
        TokenKind::Keyword(Keyword::Timestamp) => {
            // PostgreSQL accepts `TIMESTAMP '...'`, `TIMESTAMP(p) '...'`, the
            // multi-word `TIMESTAMP WITH TIME ZONE '...'` typed-literal form,
            // and the precision may sit either before or after that qualifier:
            // `TIMESTAMP(p) WITH TIME ZONE` and
            // `TIMESTAMP WITH TIME ZONE(p)` are both valid. The multi-word
            // form routes to the timestamptz variant, reusing the existing
            // timestamp-with-time-zone representation. ZONE may lex as either
            // a keyword or a plain identifier (identifiers named "zone" must
            // keep working), so accept both.
            parser.advance();
            let mut precision = parse_temporal_precision(parser)?;
            let is_with_time_zone = parser.peek_n(0).kind == TokenKind::Keyword(Keyword::With)
                && parser.peek_n(1).kind == TokenKind::Keyword(Keyword::Time)
                && (parser.peek_n(2).kind == TokenKind::Keyword(Keyword::Zone)
                    || (parser.peek_n(2).kind == TokenKind::Identifier
                        && parser.peek_n(2).lexeme.eq_ignore_ascii_case("zone")));
            if is_with_time_zone {
                parser.advance();
                parser.advance();
                parser.advance();
                if precision.is_none() {
                    precision = parse_temporal_precision(parser)?;
                }
                let s = parser
                    .consume(TokenKind::StringLiteral, "TIMESTAMP string literal")?
                    .lexeme;
                return match precision {
                    Some(p) => Ok(Expression::TypedTimestamptzLiteral {
                        text: s,
                        precision: p,
                    }),
                    None => Ok(Expression::TimestamptzLiteral(s)),
                };
            }
            let s = parser
                .consume(TokenKind::StringLiteral, "TIMESTAMP string literal")?
                .lexeme;
            match precision {
                Some(p) => Ok(Expression::TypedTimestampLiteral {
                    text: s,
                    precision: p,
                }),
                None => Ok(Expression::TimestampLiteral(s)),
            }
        }
        TokenKind::Keyword(Keyword::Timestamptz) => {
            // PostgreSQL exposes TIMESTAMPTZ as the commonly used shorthand
            // for TIMESTAMP WITH TIME ZONE. It must be recognized through the
            // normal SQL type/expression layer (not special-cased by callers
            // such as JSON_SCALAR) so the same syntax works anywhere a typed
            // literal is accepted.
            parser.advance();
            let precision = parse_temporal_precision(parser)?;
            let s = parser
                .consume(TokenKind::StringLiteral, "TIMESTAMPTZ string literal")?
                .lexeme;
            match precision {
                Some(p) => Ok(Expression::TypedTimestamptzLiteral {
                    text: s,
                    precision: p,
                }),
                None => Ok(Expression::TimestamptzLiteral(s)),
            }
        }
        TokenKind::Keyword(Keyword::Interval) => {
            parser.advance();
            let s = parser
                .consume(TokenKind::StringLiteral, "INTERVAL string literal")?
                .lexeme;
            let value = plomid_types::text::parse_value(&s, plomid_types::PgType::Interval)
                .map_err(|error| ParseError::Unsupported {
                    message: "invalid INTERVAL literal".into(),
                    detail: Some(error),
                })?;
            Ok(Expression::Literal(value))
        }
        TokenKind::Keyword(Keyword::CurrentDate) => {
            parser.advance();
            // PostgreSQL allows CURRENT_DATE / CURRENT_TIME / CURRENT_TIMESTAMP
            // with or without parentheses: `CURRENT_TIMESTAMP` and
            // `CURRENT_TIMESTAMP()` are equivalent. Accept the parenthesised
            // form only when empty.
            if parser.check(TokenKind::LParen) && parser.peek_n(1).kind == TokenKind::RParen {
                parser.advance();
                parser.advance();
            }
            Ok(Expression::FunctionCall {
                name: "current_date".to_string(),
                args: Vec::new(),
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::Keyword(Keyword::CurrentTime) => {
            parser.advance();
            if parser.check(TokenKind::LParen) && parser.peek_n(1).kind == TokenKind::RParen {
                parser.advance();
                parser.advance();
            }
            Ok(Expression::FunctionCall {
                name: "current_time".to_string(),
                args: Vec::new(),
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::Keyword(Keyword::LocalTime) => {
            parser.advance();
            if parser.check(TokenKind::LParen) && parser.peek_n(1).kind == TokenKind::RParen {
                parser.advance();
                parser.advance();
            }
            Ok(Expression::FunctionCall {
                name: "current_time".to_string(),
                args: Vec::new(),
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::Keyword(Keyword::LocalTimestamp) => {
            parser.advance();
            if parser.check(TokenKind::LParen) && parser.peek_n(1).kind == TokenKind::RParen {
                parser.advance();
                parser.advance();
            }
            Ok(Expression::FunctionCall {
                name: "current_timestamp".to_string(),
                args: Vec::new(),
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::Keyword(Keyword::CurrentTimestamp) => {
            parser.advance();
            if parser.check(TokenKind::LParen) && parser.peek_n(1).kind == TokenKind::RParen {
                parser.advance();
                parser.advance();
            }
            Ok(Expression::FunctionCall {
                name: "current_timestamp".to_string(),
                args: Vec::new(),
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: None,
                null_handling: None,
                unique_keys: None,
            })
        }
        TokenKind::Keyword(Keyword::Value) => {
            // PostgreSQL domain CHECK constraints use VALUE to refer to the
            // value being tested. Treat it as a special column reference,
            // preserving the original source text so `VALUE` and `value`
            // both work as column references.
            parser.advance();
            Ok(Expression::ColumnRef(token.lexeme.clone()))
        }
        TokenKind::LParen => {
            parser.advance();
            // Could be either a parenthesised expression or a scalar subquery.
            if parser.check(TokenKind::Keyword(Keyword::Select)) {
                let stmt = super::select::parse_select(parser)?;
                parser.consume(TokenKind::RParen, ")")?;
                return Ok(Expression::ScalarSubquery(Box::new(stmt)));
            }
            let expr = parse_expression(parser)?;
            parser.consume(TokenKind::RParen, ")")?;
            Ok(expr)
        }
        TokenKind::Star => {
            parser.advance();
            Ok(Expression::Star)
        }
        TokenKind::Keyword(Keyword::Case) => parse_case_expression(parser),
        TokenKind::Keyword(Keyword::Coalesce) => parse_coalesce(parser),
        TokenKind::Keyword(Keyword::NullIf) => parse_nullif(parser),
        TokenKind::Keyword(Keyword::Exists) => parse_exists(parser),
        TokenKind::Keyword(Keyword::Array) => parse_array_literal(parser),
        TokenKind::LBracket => parse_vector_literal(parser),
        TokenKind::Keyword(Keyword::Json) => {
            // `JSON` is dual-purpose: `JSON '...'` literal prefix AND
            // `JSON(...)` regular call. Peek: `(` means function call.
            if parser.peek_n(1).kind == TokenKind::LParen {
                let fname = token.lexeme.clone();
                parser.advance();
                parser.advance();
                let fargs = parse_json_call_args(parser)?;
                parser.consume(TokenKind::RParen, ")")?;
                return Ok(Expression::FunctionCall {
                    name: fname,
                    args: fargs.0,
                    distinct: false,
                    filter: None,
                    order_by: Vec::new(),
                    returning: fargs.1,
                    null_handling: fargs.2,
                    unique_keys: fargs.3,
                });
            }
            // SQL/JSON `JSON '...'` literal prefix: parse the following string
            // literal and wrap it as a `json('...')` function call so the executor
            // validates and coerces the JSON text. Accept an optional
            // `RETURNING <type>` clause (FIX 5: JSON_SERIALIZE(JSON '...'
            // RETURNING TEXT) nests the literal as an argument; standalone
            // `JSON '...' RETURNING json` is also valid SQL/JSON).
            parser.advance();
            let lit = parser
                .consume(TokenKind::StringLiteral, "JSON string literal")?
                .lexeme;
            let lit_returning = if parser.check_keyword(Keyword::Returning) {
                parser.advance();
                Some(parser.parse_type_name("RETURNING data type")?)
            } else {
                None
            };
            Ok(Expression::FunctionCall {
                name: "json".to_string(),
                args: vec![Expression::Literal(Value::Text(lit))],
                distinct: false,
                filter: None,
                order_by: Vec::new(),
                returning: lit_returning,
                null_handling: None,
                unique_keys: None,
            })
        }
        _ => {
            let name = parser.parse_qualified_identifier("column name or expression")?;
            if name.eq_ignore_ascii_case("json_table") {
                return parse_json_table_call(parser);
            }
            if parser.check(TokenKind::LParen) {
                parser.advance();
                let mut args = Vec::new();
                let mut has_all = false;
                let distinct = parser.check(TokenKind::Keyword(Keyword::Distinct));
                if distinct {
                    parser.advance();
                }
                if parser.check(TokenKind::Star) {
                    parser.advance();
                    has_all = true;
                } else if !parser.check(TokenKind::RParen) {
                    // Special SQL-standard function syntaxes that use
                    // keyword separators (IN, FROM, FOR) rather than
                    // commas.  These keywords are NOT expression operators,
                    // so we must intercept them before parse_expression
                    // has a chance to consume them (IN would otherwise be
                    // treated as the expr IN (...) operator).
                    let lname = name.to_ascii_lowercase();
                    let bare = lname.rsplit('.').next().unwrap_or(&lname).to_string();
                    if bare == "position" {
                        // POSITION(substring IN string) -- args become
                        // [substring, string].  Use parse_concat for the
                        // first arg so the IN keyword is not consumed as
                        // a comparison operator.
                        args.push(parse_concat(parser)?);
                        if parser.check(TokenKind::Keyword(Keyword::In)) {
                            parser.advance();
                            args.push(parse_expression(parser)?);
                        } else {
                            while parser.check(TokenKind::Comma) {
                                parser.advance();
                                args.push(parse_expression(parser)?);
                            }
                        }
                    } else if bare == "json_object" || bare == "jsonb_object" {
                        // SQL/JSON `json_object(KEY k1 VALUE v1, KEY k2 VALUE v2, ...)`
                        // in addition to the ordinary `json_object(array[k,v,...])`
                        // form that parse_expression handles.
                        parse_json_object_pairs(parser, &mut args)?;
                    } else if bare == "json_objectagg" || bare == "jsonb_objectagg" {
                        // SQL/JSON `JSON_OBJECTAGG(KEY k VALUE v [ORDER BY ...])`
                        // and `JSONB_OBJECTAGG(KEY k VALUE v)` use keyword-separated
                        // arguments (KEY ... VALUE ...), not comma-separated.
                        // PostgreSQL aggregate forms `json_object_agg(k, v)` and
                        // `jsonb_object_agg(k, v)` are handled by the else branch
                        // below — they use ordinary comma-separated argument lists.
                        if parser.check_keyword(Keyword::Key) {
                            parser.advance();
                            args.push(parse_expression(parser)?);
                            if parser.check_keyword(Keyword::Value) {
                                parser.advance();
                                args.push(parse_expression(parser)?);
                            }
                        } else {
                            args.push(parse_expression(parser)?);
                            while parser.check(TokenKind::Comma) {
                                parser.advance();
                                args.push(parse_expression(parser)?);
                            }
                        }
                    } else if bare == "json_object_agg" || bare == "jsonb_object_agg" {
                        // PostgreSQL aggregate `json_object_agg(key, value)` /
                        // `jsonb_object_agg(key, value)` — ordinary comma-separated
                        // argument list, NOT the SQL/JSON KEY/Value syntax.
                        args.push(parse_expression(parser)?);
                        while parser.check(TokenKind::Comma) {
                            parser.advance();
                            args.push(parse_expression(parser)?);
                        }
                    } else {
                        args.push(parse_expression(parser)?);
                        if bare == "substring" && parser.check(TokenKind::Keyword(Keyword::From)) {
                            // SUBSTRING(str FROM start [FOR len])
                            parser.advance();
                            args.push(parse_expression(parser)?);
                            if parser.check(TokenKind::Keyword(Keyword::For)) {
                                parser.advance();
                                args.push(parse_expression(parser)?);
                            }
                        } else {
                            while parser.check(TokenKind::Comma) {
                                // Trailing `, RETURNING ...` / `, NULL ON NULL`
                                // / `, ABSENT ON NULL` / `, WITH UNIQUE KEYS`
                                // etc: stop argument parsing so the clause loop
                                // below consumes the clause instead of choking.
                                // NULL/ABSENT alone are VALUES (JSON_ARRAY(1,NULL,2))
                                // — only break when followed by ON.
                                let n1 = parser.peek_n(1).kind;
                                let n1_is_null_absent = n1 == TokenKind::Keyword(Keyword::Null)
                                    || n1 == TokenKind::Keyword(Keyword::Absent);
                                let n2 = parser.peek_n(2);
                                let n2_is_on = n2.kind == TokenKind::Keyword(Keyword::On)
                                    || n2.lexeme.eq_ignore_ascii_case("on");
                                if n1 == TokenKind::Keyword(Keyword::Returning)
                                    || n1 == TokenKind::Keyword(Keyword::With)
                                    || n1 == TokenKind::Keyword(Keyword::Without)
                                    || n1 == TokenKind::Keyword(Keyword::Default)
                                    || n1 == TokenKind::Keyword(Keyword::Error)
                                    || n1 == TokenKind::Keyword(Keyword::Format)
                                    || (n1_is_null_absent && n2_is_on)
                                {
                                    break;
                                }
                                parser.advance();
                                // Bare `NULL ON NULL` / `ABSENT ON NULL` /
                                // `RETURNING ...` without a preceding comma
                                // (SQL/JSON constructor syntax): stop before
                                // consuming the clause keyword as a value.
                                if parser.check_keyword(Keyword::Returning)
                                    || parser.check_keyword(Keyword::With)
                                    || parser.check_keyword(Keyword::Without)
                                    || parser.check_keyword(Keyword::Default)
                                    || parser.check_keyword(Keyword::Error)
                                    || parser.check_keyword(Keyword::Format)
                                {
                                    break;
                                }
                                if parser.check_keyword(Keyword::Null)
                                    || parser.check_keyword(Keyword::Absent)
                                {
                                    let is_clause = parser.peek_n(1).kind
                                        == TokenKind::Keyword(Keyword::On)
                                        || parser.peek_n(1).lexeme.eq_ignore_ascii_case("on");
                                    if is_clause {
                                        break;
                                    }
                                }
                                args.push(parse_expression(parser)?);
                            }
                        }
                    }
                }
                // Optional ORDER BY inside the function call: func(args ORDER BY
                // expr [ASC|DESC] [NULLS FIRST|NULLS LAST]). This is primarily
                // meaningful for aggregate function calls, but we parse it for any
                // function call and let the executor validate usage.
                //
                // IMPORTANT: Check for ORDER BY BEFORE consuming the closing `)`
                // because PostgreSQL allows aggregate ORDER BY to appear inside the
                // parentheses: `json_agg(value ORDER BY value)`.
                let order_by = if parser.check(TokenKind::Keyword(Keyword::Order)) {
                    parser.advance();
                    parse_aggregate_order_by(parser)?
                } else {
                    Vec::new()
                };
                // Parse NULL ON NULL / ABSENT ON NULL aggregates:
                // JSON_ARRAYAGG(x NULL ON NULL) and similar. Only treat as a
                // clause when followed by ON (else it may be a value arg or
                // `NULL ON ERROR` swallowable form handled below).
                let mut null_handling: Option<crate::ast::NullHandling> = None;
                if parser.check_keyword(Keyword::Null) || parser.check_keyword(Keyword::Absent) {
                    let is_clause = parser.peek_n(1).kind == TokenKind::Keyword(Keyword::On)
                        || parser.peek_n(1).lexeme.eq_ignore_ascii_case("on");
                    if is_clause {
                        // `X ON NULL` sets null_handling. `X ON EMPTY` /
                        // `X ON ERROR` are JSON_VALUE/JSON_QUERY behavior
                        // forms — swallow them here so the clause loop sees
                        // a clean position (do NOT consume-then-require NULL).
                        let target_is_null = parser.peek_n(2).kind
                            == TokenKind::Keyword(Keyword::Null)
                            || parser.peek_n(2).lexeme.eq_ignore_ascii_case("null");
                        let target = parser.peek_n(2).lexeme.to_ascii_lowercase();
                        if target_is_null {
                            if parser.check_keyword(Keyword::Null) {
                                parser.advance();
                                parser.consume(TokenKind::Keyword(Keyword::On), "ON")?;
                                parser.consume(TokenKind::Keyword(Keyword::Null), "NULL")?;
                                null_handling = Some(crate::ast::NullHandling::NullOnNull);
                            } else {
                                parser.advance();
                                parser.consume(TokenKind::Keyword(Keyword::On), "ON")?;
                                parser.consume(TokenKind::Keyword(Keyword::Null), "NULL")?;
                                null_handling = Some(crate::ast::NullHandling::AbsentOnNull);
                            }
                        } else if target == "empty" || target == "error" {
                            parser.advance(); // NULL / ABSENT
                            parser.advance(); // ON
                            parser.advance(); // EMPTY / ERROR
                        }
                    }
                }
                // Parse SQL/JSON constructor clauses (RETURNING, NULL ON NULL,
                // ABSENT ON NULL, WITH [UNIQUE] KEYS, etc.) that appear before
                // the closing ) inside a JSON constructor call.
                let mut returning: Option<String> = None;
                let mut unique_keys: Option<bool> = None;
                // `KEYS` lexes as a plain identifier (only singular KEY is a
                // keyword), so `WITH UNIQUE KEYS` needs lexeme matching here.
                let is_keys_word = |parser: &Parser<'_>| {
                    parser.check_keyword(Keyword::Key)
                        || parser.peek().lexeme.eq_ignore_ascii_case("keys")
                };
                loop {
                    if parser.check(TokenKind::RParen) {
                        break;
                    }
                    // Allow an optional comma before each trailing clause:
                    // `..., NULL ON NULL)` / `..., RETURNING json)`.
                    if parser.check(TokenKind::Comma) && is_trailing_clause_ahead(parser, 1) {
                        parser.advance();
                        continue;
                    }
                    // Comma-separated NULL ON NULL / ABSENT ON NULL (SQL/JSON
                    // constructor form `JSON_ARRAY(1, NULL, 2, NULL ON NULL)`):
                    // the clause keywords were NOT consumed as args (the arg
                    // loop breaks on `, NULL ON` lookahead), so parse the
                    // clause directly WITHOUT popping — args.last() here is a
                    // legitimate value (e.g. KEY 'b' VALUE NULL), not spurious.
                    if parser.check_keyword(Keyword::Null) || parser.check_keyword(Keyword::Absent)
                    {
                        let is_clause = parser.peek_n(1).kind == TokenKind::Keyword(Keyword::On)
                            || parser.peek_n(1).lexeme.eq_ignore_ascii_case("on");
                        if is_clause {
                            // `X ON NULL` sets null_handling; `X ON EMPTY` /
                            // `X ON ERROR` are JSON_VALUE/JSON_QUERY behavior
                            // forms — swallow those for forwards-compatibility.
                            let target_is_null = parser.peek_n(2).kind
                                == TokenKind::Keyword(Keyword::Null)
                                || parser.peek_n(2).lexeme.eq_ignore_ascii_case("null");
                            if target_is_null {
                                if parser.check_keyword(Keyword::Null) {
                                    parser.advance();
                                    parser.consume(TokenKind::Keyword(Keyword::On), "ON")?;
                                    parser.consume(TokenKind::Keyword(Keyword::Null), "NULL")?;
                                    null_handling = Some(crate::ast::NullHandling::NullOnNull);
                                } else {
                                    parser.advance();
                                    parser.consume(TokenKind::Keyword(Keyword::On), "ON")?;
                                    parser.consume(TokenKind::Keyword(Keyword::Null), "NULL")?;
                                    null_handling = Some(crate::ast::NullHandling::AbsentOnNull);
                                }
                                continue;
                            }
                            let target = parser.peek_n(2).lexeme.to_ascii_lowercase();
                            if target == "empty" || target == "error" {
                                parser.advance(); // NULL / ABSENT
                                parser.advance(); // ON
                                parser.advance(); // EMPTY / ERROR
                                continue;
                            }
                        }
                    }
                    // `EMPTY [ARRAY] ON EMPTY|ERROR|NULL` (JSON_QUERY): what
                    // to return when the path yields no value.
                    if parser.check_keyword(Keyword::Empty) {
                        let next = parser.peek_n(1).lexeme.to_ascii_lowercase();
                        if next == "array" || next == "on" {
                            parser.advance(); // EMPTY
                            if parser.peek().lexeme.eq_ignore_ascii_case("array") {
                                parser.advance(); // ARRAY
                            }
                            if parser.check_keyword(Keyword::On) {
                                parser.advance(); // ON
                                let tail = parser.peek().lexeme.to_ascii_lowercase();
                                if tail == "empty" || tail == "error" || tail == "null" {
                                    parser.advance();
                                }
                            }
                            continue;
                        }
                    }
                    // `UNKNOWN ON ERROR|EMPTY` (JSON_EXISTS three-valued form).
                    if parser.peek().lexeme.eq_ignore_ascii_case("unknown") {
                        let next = parser.peek_n(1).lexeme.to_ascii_lowercase();
                        if next == "on" {
                            parser.advance(); // UNKNOWN
                            parser.advance(); // ON
                            let tail = parser.peek().lexeme.to_ascii_lowercase();
                            if tail == "empty" || tail == "error" || tail == "null" {
                                parser.advance();
                            }
                            continue;
                        }
                    }
                    if null_handling.is_none() && parser.check_keyword(Keyword::Null) {
                        let is_clause = parser.peek_n(1).kind == TokenKind::Keyword(Keyword::On)
                            || parser.peek_n(1).lexeme.eq_ignore_ascii_case("on");
                        if !is_clause {
                            break;
                        }
                        parser.advance();
                        parser.consume(TokenKind::Keyword(Keyword::On), "ON")?;
                        parser.consume(TokenKind::Keyword(Keyword::Null), "NULL")?;
                        null_handling = Some(crate::ast::NullHandling::AbsentOnNull);
                        continue;
                    }
                    if returning.is_none() && parser.check_keyword(Keyword::Returning) {
                        parser.advance();
                        let type_name = parser.parse_type_name("RETURNING data type")?;
                        returning = Some(type_name);
                        continue;
                    }
                    if unique_keys.is_none() && parser.check_keyword(Keyword::With) {
                        // WITH UNIQUE KEYS vs WITH WRAPPER: peek ahead so
                        // `WITHOUT WRAPPER`-style JSON_QUERY forms are not
                        // consumed as UNIQUE KEYS (which demands KEY/KEYS).
                        let next = parser.peek_n(1).lexeme.to_ascii_lowercase();
                        let looks_like_keys = next == "unique"
                            || next == "key"
                            || next == "keys"
                            || parser.peek_n(1).kind == TokenKind::Keyword(Keyword::Key);
                        if looks_like_keys {
                            parser.advance();
                            if parser.check_keyword(Keyword::Unique) {
                                parser.advance();
                            }
                            // Optional KEY/KEYS: PostgreSQL allows both
                            // `WITH UNIQUE KEYS` and bare `WITH UNIQUE`.
                            if is_keys_word(parser) {
                                parser.advance();
                            }
                            unique_keys = Some(true);
                            continue;
                        }
                        // Not UNIQUE KEYS: fall through to the WRAPPER
                        // handler below (break would skip it).
                    }
                    if unique_keys.is_none() && parser.check_keyword(Keyword::Without) {
                        // WITHOUT UNIQUE KEYS vs WITHOUT WRAPPER: same guard.
                        let next2 = parser.peek_n(1).lexeme.to_ascii_lowercase();
                        let looks_like_keys2 = next2 == "unique"
                            || next2 == "key"
                            || next2 == "keys"
                            || parser.peek_n(1).kind == TokenKind::Keyword(Keyword::Key);
                        if !looks_like_keys2 {
                            // Fall through to the WRAPPER handler below.
                        } else {
                            parser.advance();
                            if parser.check_keyword(Keyword::Unique) {
                                parser.advance();
                            }
                            // Optional KEY/KEYS: bare `WITHOUT UNIQUE` too.
                            if is_keys_word(parser) {
                                parser.advance();
                            }
                            unique_keys = Some(false);
                            continue;
                        }
                    }
                    // JSON_VALUE / JSON_QUERY style DEFAULT ... ON ERROR / ON EMPTY,
                    // ERROR ON ERROR, NULL ON ERROR. Keep parsing so the
                    // statement does not choke on the keyword; the executor can
                    // add semantics later.
                    if parser.check_keyword(Keyword::Default) {
                        parser.advance();
                        // Parse the default expression, then consume ON ERROR/EMPTY
                        let _default_val = parse_expression(parser)?;
                        if parser.check_keyword(Keyword::On) {
                            parser.advance();
                            if parser.check_keyword(Keyword::Error)
                                || parser.check_keyword(Keyword::Empty)
                            {
                                parser.advance();
                            }
                        }
                        continue;
                    }
                    if parser.check_keyword(Keyword::Error) {
                        parser.advance();
                        if parser.check_keyword(Keyword::On) {
                            parser.advance();
                            if parser.check_keyword(Keyword::Error)
                                || parser.check_keyword(Keyword::Empty)
                            {
                                parser.advance();
                            }
                        }
                        continue;
                    }
                    if parser.check_keyword(Keyword::Null) || parser.check_keyword(Keyword::Absent)
                    {
                        // NULL ON EMPTY / NULL ON ERROR / ABSENT ON EMPTY /
                        // ABSENT ON ERROR forms are swallowed here for
                        // forwards-compatibility so the parser doesn't choke.
                        // NOTE: a bare `NULL ON NULL` / `ABSENT ON NULL` that
                        // reaches this point means null_handling was already
                        // set — still swallow it instead of erroring.
                        let first_tok = parser.peek().clone();
                        parser.advance();
                        if parser.check_keyword(Keyword::On) {
                            parser.advance();
                            if parser.check_keyword(Keyword::Error)
                                || parser.check_keyword(Keyword::Empty)
                                || parser.check_keyword(Keyword::Null)
                            {
                                parser.advance();
                            }
                        }
                        let _ = first_tok;
                        continue;
                    }
                    // EMPTY [ARRAY|OBJECT] ON ERROR / ON EMPTY (JSON_QUERY).
                    if parser.check_keyword(Keyword::Empty) {
                        parser.advance();
                        let lex = parser.peek().lexeme.to_ascii_lowercase();
                        if lex == "array" || lex == "object" {
                            parser.advance();
                        }
                        if parser.check_keyword(Keyword::On) {
                            parser.advance();
                            if parser.check_keyword(Keyword::Error)
                                || parser.check_keyword(Keyword::Empty)
                            {
                                parser.advance();
                            }
                        }
                        continue;
                    }
                    // TRUE/FALSE ON ERROR (JSON_EXISTS).
                    if parser.check_keyword(Keyword::True) || parser.check_keyword(Keyword::False) {
                        // Only swallow when followed by ON (else a real arg).
                        let is_clause = parser.peek_n(1).kind == TokenKind::Keyword(Keyword::On)
                            || parser.peek_n(1).lexeme.eq_ignore_ascii_case("on");
                        if is_clause {
                            parser.advance();
                            parser.advance(); // ON
                            if parser.check_keyword(Keyword::Error)
                                || parser.check_keyword(Keyword::Empty)
                            {
                                parser.advance();
                            }
                            continue;
                        }
                        break;
                    }
                    // WITHOUT WRAPPER / WITH WRAPPER forms (JSON_QUERY style).
                    // Must run BEFORE the WITHOUT/WITH UNIQUE KEYS handlers
                    // above? No — WITHOUT UNIQUE KEYS and WITH UNIQUE KEYS
                    // are prefix-matched first. Here we only swallow WRAPPER
                    // variants: check the word after WITHOUT/WITH.
                    if parser.check_keyword(Keyword::Without) {
                        let next = parser.peek_n(1).lexeme.to_ascii_lowercase();
                        let is_wrapper = next == "wrapper" || next == "array";
                        let is_unique = next == "unique"
                            || parser.peek_n(1).kind == TokenKind::Keyword(Keyword::Key)
                            || next == "key"
                            || next == "keys";
                        if !is_wrapper && !is_unique {
                            break;
                        }
                        if is_unique {
                            break; // handled by UNIQUE KEYS loop above
                        }
                        parser.advance();
                        // WITHOUT WRAPPER / WITHOUT ARRAY WRAPPER
                        // Consume "WRAPPER" / "ARRAY WRAPPER" if present.
                        if parser.peek().lexeme.eq_ignore_ascii_case("wrapper")
                            || parser.peek().lexeme.eq_ignore_ascii_case("array")
                        {
                            parser.advance();
                            if parser.peek().lexeme.eq_ignore_ascii_case("wrapper") {
                                parser.advance();
                            }
                        }
                        continue;
                    }
                    if parser.check_keyword(Keyword::With) {
                        let next = parser.peek_n(1).lexeme.to_ascii_lowercase();
                        let is_wrapper = next == "wrapper"
                            || next == "array"
                            || next == "conditional"
                            || next == "unconditional";
                        if !is_wrapper {
                            break; // WITH UNIQUE KEYS handled above
                        }
                        // WITH WRAPPER / WITH ARRAY WRAPPER / WITH CONDITIONAL WRAPPER
                        parser.advance();
                        let wrap_lex = parser.peek().lexeme.to_ascii_lowercase();
                        if wrap_lex == "wrapper"
                            || wrap_lex == "array"
                            || wrap_lex == "conditional"
                            || wrap_lex == "unconditional"
                        {
                            parser.advance();
                            if parser.peek().lexeme.eq_ignore_ascii_case("wrapper") {
                                parser.advance();
                            }
                        }
                        continue;
                    }
                    // FORMAT JSON / FORMAT JSON ENCODING ...
                    if parser.check_keyword(Keyword::Format) {
                        parser.advance();
                        if parser.peek().lexeme.eq_ignore_ascii_case("json") {
                            parser.advance();
                        }
                        continue;
                    }
                    break;
                }
                parser.consume(TokenKind::RParen, ")")?;
                let name = name.rsplit('.').next().unwrap_or(&name).to_string();
                if has_all {
                    args.push(Expression::Star);
                }
                let filter = if parser.check(TokenKind::Keyword(Keyword::Filter)) {
                    parser.advance();
                    parser.consume(TokenKind::LParen, "(")?;
                    parser.consume(TokenKind::Keyword(Keyword::Where), "WHERE")?;
                    let filter_expr = parse_expression(parser)?;
                    parser.consume(TokenKind::RParen, ")")?;
                    Some(Box::new(filter_expr))
                } else {
                    None
                };
                // Detect a window function: name(...) OVER (...)
                if parser.check(TokenKind::Keyword(Keyword::Over)) {
                    parser.advance();
                    let over = super::select::parse_window_spec(parser)?;
                    return Ok(Expression::WindowFunction { name, args, over });
                }
                Ok(Expression::FunctionCall {
                    name,
                    args,
                    distinct,
                    filter,
                    order_by,
                    returning,
                    null_handling,
                    unique_keys,
                })
            } else {
                Ok(Expression::ColumnRef(name))
            }
        }
    }
}

/// Parses `ORDER BY expr [ASC|DESC] [NULLS FIRST|NULLS LAST]` inside an
/// aggregate function call (e.g. `jsonb_agg(x ORDER BY x DESC NULLS FIRST)`).
/// Mirrors the item-parsing logic already used for query-level ORDER BY and
/// window-spec ORDER BY in `select.rs`, kept private to the expression parser.
fn parse_aggregate_order_by(parser: &mut Parser<'_>) -> Result<Vec<OrderByItem>, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::By), "BY")?;
    let mut items = Vec::new();
    loop {
        let expr = parse_expression(parser)?;
        let descending = if parser.check_keyword(Keyword::Desc) {
            parser.advance();
            true
        } else if parser.check_keyword(Keyword::Asc) {
            parser.advance();
            false
        } else {
            false
        };
        let nulls_first = if parser.check_keyword(Keyword::Nulls) {
            parser.advance();
            if parser.check_keyword(Keyword::First) {
                parser.advance();
                Some(true)
            } else if parser.check_keyword(Keyword::Last) {
                parser.advance();
                Some(false)
            } else {
                return Err(ParseError::unexpected(
                    parser.peek(),
                    "FIRST or LAST after NULLS",
                ));
            }
        } else {
            None
        };
        items.push(OrderByItem {
            expr,
            descending,
            nulls_first,
        });
        if !parser.check(TokenKind::Comma) {
            break;
        }
        parser.advance();
    }
    Ok(items)
}

fn parse_cast_expression(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::Cast), "CAST")?;
    parser.consume(TokenKind::LParen, "(")?;
    let expr = parse_expression(parser)?;
    parser.consume(TokenKind::Keyword(Keyword::As), "AS")?;
    let type_name = parser.parse_type_name("type name")?;
    parser.consume(TokenKind::RParen, ")")?;
    Ok(Expression::Cast {
        expr: Box::new(expr),
        type_name,
    })
}

fn parse_extract_expression(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::Extract), "EXTRACT")?;
    parser.consume(TokenKind::LParen, "(")?;
    let field_token = parser.peek().clone();
    let field = match field_token.kind {
        TokenKind::Identifier | TokenKind::Keyword(_) => {
            parser.advance();
            field_token.lexeme.clone()
        }
        _ => return Err(ParseError::unexpected(&field_token, "field name")),
    };
    parser.consume(TokenKind::Keyword(Keyword::From), "FROM")?;
    let expr = parse_expression(parser)?;
    parser.consume(TokenKind::RParen, ")")?;
    Ok(Expression::Extract {
        field,
        expr: Box::new(expr),
    })
}

fn parse_case_expression(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::Case), "CASE")?;
    let mut operand = None;
    if !parser.check(TokenKind::Keyword(Keyword::When)) {
        operand = Some(Box::new(parser.parse_expression()?));
    }
    let mut whens = Vec::new();
    while parser.check(TokenKind::Keyword(Keyword::When)) {
        parser.advance();
        let cond = parser.parse_expression()?;
        parser.consume(TokenKind::Keyword(Keyword::Then), "THEN")?;
        let value = parser.parse_expression()?;
        whens.push((cond, value));
    }
    let default = if parser.check(TokenKind::Keyword(Keyword::Else)) {
        parser.advance();
        Some(Box::new(parser.parse_expression()?))
    } else {
        None
    };
    parser.consume(TokenKind::Keyword(Keyword::End), "END")?;
    Ok(Expression::Case {
        operand,
        whens,
        default,
    })
}

fn parse_coalesce(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::Coalesce), "COALESCE")?;
    parser.consume(TokenKind::LParen, "(")?;
    let mut args = Vec::new();
    loop {
        args.push(parser.parse_expression()?);
        if !parser.check(TokenKind::Comma) {
            break;
        }
        parser.advance();
    }
    parser.consume(TokenKind::RParen, ")")?;
    Ok(Expression::Coalesce(args))
}

fn parse_nullif(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::NullIf), "NULLIF")?;
    parser.consume(TokenKind::LParen, "(")?;
    let a = parser.parse_expression()?;
    parser.consume(TokenKind::Comma, ",")?;
    let b = parser.parse_expression()?;
    parser.consume(TokenKind::RParen, ")")?;
    Ok(Expression::NullIf(Box::new(a), Box::new(b)))
}

fn parse_exists(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::Exists), "EXISTS")?;
    parser.consume(TokenKind::LParen, "(")?;
    let stmt = super::select::parse_select(parser)?;
    parser.consume(TokenKind::RParen, ")")?;
    Ok(Expression::Exists(Box::new(stmt)))
}

fn parse_array_literal(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::Keyword(Keyword::Array), "ARRAY")?;
    // PostgreSQL also accepts ARRAY(SELECT ...), which is emitted by psql's
    // catalog queries when expanding role OIDs.  Preserve the subquery as an
    // expression so the normal executor can evaluate it; this is distinct
    // from the ARRAY[...] constructor below.
    if parser.check(TokenKind::LParen) {
        parser.advance();
        let subquery = super::select::parse_select(parser)?;
        parser.consume(TokenKind::RParen, ")")?;
        return Ok(Expression::FunctionCall {
            name: "array".to_string(),
            args: vec![Expression::ScalarSubquery(Box::new(subquery))],
            distinct: false,
            filter: None,
            order_by: Vec::new(),
            returning: None,
            null_handling: None,
            unique_keys: None,
        });
    }
    parser.consume(TokenKind::LBracket, "[")?;
    let mut elements = Vec::new();
    if !parser.check(TokenKind::RBracket) {
        loop {
            elements.push(parser.parse_expression()?);
            if !parser.check(TokenKind::Comma) {
                break;
            }
            parser.advance();
        }
    }
    parser.consume(TokenKind::RBracket, "]")?;
    // Store as a function call with name `array` and the element list.
    Ok(Expression::FunctionCall {
        name: "array".to_string(),
        args: elements,
        distinct: false,
        filter: None,
        order_by: Vec::new(),
        returning: None,
        null_handling: None,
        unique_keys: None,
    })
}

/// Parses a native dense vector literal: `[0.12, -0.34, 1e3, ...]`.
///
/// A bare `[` at the start of a primary expression can only open a vector
/// literal: array subscripting (`arr[1]`) is a postfix operator handled in
/// `parse_primary`, and `ARRAY[...]` keeps its own keyword-prefixed rule.
/// Elements are comma-separated numeric literals with optional `+`/`-`
/// signs. All validation (finite, non-empty, dimension cap) delegates to
/// `plomid-vector`'s canonical dense parser, so SQL carries no duplicate
/// vector logic; malformed shapes fail as `VECTOR_INVALID_LITERAL`.
fn parse_vector_literal(parser: &mut Parser<'_>) -> Result<Expression, ParseError> {
    parser.consume(TokenKind::LBracket, "[")?;
    // Collect element spellings (with signs) to replay through the canonical
    // dense parser. Token-level checks below turn malformed shapes into
    // `VECTOR_INVALID_LITERAL` errors instead of generic syntax errors.
    let mut elements: Vec<String> = Vec::new();
    if parser.check(TokenKind::RBracket) {
        parser.advance();
        return Err(ParseError::Unsupported {
            message: "VECTOR_INVALID_LITERAL: dense vector must not be empty".into(),
            detail: None,
        });
    }
    loop {
        let mut spelling = String::new();
        if parser.check(TokenKind::Minus) {
            spelling.push('-');
            parser.advance();
        } else if parser.check(TokenKind::Plus) {
            parser.advance();
        }
        let token = parser.peek().clone();
        match token.kind {
            TokenKind::IntegerLiteral => {
                spelling.push_str(&token.lexeme);
                parser.advance();
            }
            _ => {
                return Err(ParseError::Unsupported {
                    message: format!(
                        "VECTOR_INVALID_LITERAL: expected a numeric element, found '{}'",
                        token.lexeme
                    ),
                    detail: None,
                });
            }
        }
        elements.push(spelling);
        if parser.check(TokenKind::Comma) {
            parser.advance();
            // A trailing comma (`[1,2,]`) leaves an empty coordinate.
            if parser.check(TokenKind::RBracket) {
                return Err(ParseError::Unsupported {
                    message: "VECTOR_INVALID_LITERAL: empty dense coordinate".into(),
                    detail: None,
                });
            }
        } else if parser.check(TokenKind::RBracket) {
            break;
        } else {
            let token = parser.peek().clone();
            return Err(ParseError::Unsupported {
                message: format!(
                    "VECTOR_INVALID_LITERAL: expected ',' or ']', found '{}'",
                    token.lexeme
                ),
                detail: None,
            });
        }
    }
    parser.consume(TokenKind::RBracket, "]")?;
    let canonical = format!("[{}]", elements.join(","));
    let dense = plomid_vector::literal::parse_dense(&canonical, None).map_err(|error| {
        ParseError::Unsupported {
            message: format!("VECTOR_INVALID_LITERAL: {error}"),
            detail: None,
        }
    })?;
    Ok(Expression::VectorLiteral(dense.values_f32))
}

/// Parses a SQL literal value.
///
/// Supports optional unary `+`/`-` prefixes so negative numbers are valid
/// in direct value contexts (INSERT VALUES, literals) as well as through the
/// full expression grammar.
pub fn parse_value(parser: &mut Parser<'_>) -> Result<Value, ParseError> {
    let negative = if parser.check(TokenKind::Minus) {
        parser.advance();
        true
    } else {
        if parser.check(TokenKind::Plus) {
            parser.advance();
        }
        false
    };
    let token = parser.peek().clone();
    match token.kind {
        TokenKind::IntegerLiteral => {
            parser.advance();
            let lex = token.lexeme.clone();
            if lex.contains('.') || lex.contains('e') || lex.contains('E') {
                // Float / decimal literal. The spelling decides the type, not
                // the value: `3.0` is a floating-point literal even though its
                // value is integral (PostgreSQL types it `numeric`). Folding
                // integral-valued decimals to Int silently reroutes `/` into
                // integer division (`3.0 / 2.0` must be 1.5, not 1) and
                // desynchronizes the runtime value from the declared result
                // type, so every decimal/exponent spelling stays Float8 here.
                if let Ok(f) = lex.parse::<f64>() {
                    let f = if negative { -f } else { f };
                    return Ok(Value::Float8(f));
                }
                return Err(ParseError::unexpected(&token, "valid numeric literal"));
            }
            // Try i64 first for performance; fall back to NUMERIC for values
            // outside the i64 range. Keep the literal text lossless until
            // type resolution; PostgreSQL numeric literals are not inherently
            // limited to i64.
            let numeric_text = if negative {
                format!("-{}", lex)
            } else {
                lex.clone()
            };
            if let Ok(num) = lex.parse::<i64>() {
                let num = if negative {
                    num.checked_neg().ok_or_else(|| {
                        ParseError::unexpected(&token, "integer literal within valid i64 range")
                    })?
                } else {
                    num
                };
                return Ok(if let Ok(int4) = i32::try_from(num) {
                    Value::Int4(int4)
                } else {
                    Value::Int8(num)
                });
            }
            // Value is outside i64 range or negation overflowed; preserve
            // the exact text as a NUMERIC value.
            let numeric = plomid_types::Numeric::parse(&numeric_text)
                .map_err(|_| ParseError::unexpected(&token, "valid numeric literal"))?;
            Ok(Value::Numeric(numeric))
        }
        TokenKind::StringLiteral => {
            parser.advance();
            if negative {
                return Err(ParseError::unexpected(
                    &token,
                    "cannot apply unary minus to string literal",
                ));
            }
            Ok(Value::Text(token.lexeme.clone()))
        }
        TokenKind::BitLiteral => {
            parser.advance();
            if negative {
                return Err(ParseError::unexpected(
                    &token,
                    "cannot apply unary minus to bit literal",
                ));
            }
            // Parse bit-string literal into PgValue::Bit.
            // PostgreSQL bit literals are sequences of '0' and '1' characters.
            // We validate the content and convert to a packed byte representation.
            let bits = token.lexeme.clone();
            let bit_len = bits.len() as u32;

            // Validate that the bit string contains only '0' and '1' characters.
            if !bits.chars().all(|c| c == '0' || c == '1') {
                return Err(ParseError::Unsupported {
                    message: "invalid bit literal: contains non-binary characters".to_string(),
                    detail: Some(format!(
                        "bit string '{bits}' must contain only 0 and 1 characters"
                    )),
                });
            }

            // Pack bits into bytes (most significant bit first, PostgreSQL style).
            // Each byte stores up to 8 bits, with the first bit in the string
            // being the most significant bit of the first byte.
            let num_bytes = bit_len.div_ceil(8);
            let mut bytes = Vec::with_capacity(num_bytes as usize);
            for chunk in bits.as_bytes().chunks(8) {
                let mut byte = 0u8;
                for &b in chunk {
                    byte = (byte << 1) | (b - b'0');
                }
                // Shift left for remaining bits in the last byte.
                let remaining = 8 - chunk.len();
                byte <<= remaining;
                bytes.push(byte);
            }

            Ok(Value::Bit {
                len: bit_len,
                bytes,
            })
        }
        TokenKind::Keyword(Keyword::Null) => {
            parser.advance();
            Ok(Value::Null)
        }
        TokenKind::Keyword(Keyword::True) => {
            parser.advance();
            if negative {
                return Err(ParseError::unexpected(
                    &token,
                    "cannot apply unary minus to boolean literal",
                ));
            }
            Ok(Value::Bool(true))
        }
        TokenKind::Keyword(Keyword::False) => {
            parser.advance();
            if negative {
                return Err(ParseError::unexpected(
                    &token,
                    "cannot apply unary minus to boolean literal",
                ));
            }
            Ok(Value::Bool(false))
        }
        _ => Err(ParseError::unexpected(
            &token,
            "value (integer or string literal)",
        )),
    }
}

/// Consumes an identifier matching `expected` (case-insensitive).
/// Also accepts a keyword token with the same lexeme so words that became
/// reserved keywords (e.g. PATH) keep parsing in JSON_TABLE clauses.
pub(super) fn consume_identifier(
    parser: &mut Parser<'_>,
    expected: &str,
    what: &str,
) -> Result<(), ParseError> {
    if parser.check_identifier(expected)
        || matches!(parser.peek().kind, TokenKind::Keyword(_)
            if parser.peek().lexeme.eq_ignore_ascii_case(expected))
    {
        parser.advance();
        return Ok(());
    }
    let token = parser.peek().clone();
    Err(ParseError::unexpected(&token, what))
}

/// Parses a single-quoted string literal and returns its content.
pub(super) fn parse_quoted_string(parser: &mut Parser<'_>) -> Result<String, ParseError> {
    let token = parser.peek().clone();
    if !matches!(token.kind, TokenKind::StringLiteral) {
        return Err(ParseError::unexpected(&token, "a string literal"));
    }
    parser.advance();
    Ok(token.lexeme)
}
